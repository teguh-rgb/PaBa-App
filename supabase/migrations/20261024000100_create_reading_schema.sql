create table if not exists public.materi (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  judul text not null,
  konten_asli text not null,
  konten_genz text,
  konten_sederhana text,
  kategori text not null,
  url_meme text,
  sort_order integer not null default 1000,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists materi_sort_order_idx
  on public.materi (sort_order, id);

alter table public.materi enable row level security;

drop policy if exists "Published reading materials are public" on public.materi;
create policy "Published reading materials are public"
  on public.materi
  for select
  to anon, authenticated
  using (true);

grant usage on schema public to anon, authenticated;
grant select on public.materi to anon, authenticated;

create table if not exists public.bookmarks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  material_id bigint not null references public.materi (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint bookmarks_user_material_unique unique (user_id, material_id)
);

create index if not exists bookmarks_user_created_idx
  on public.bookmarks (user_id, created_at desc);

alter table public.bookmarks enable row level security;

drop policy if exists "Users can read their own bookmarks" on public.bookmarks;
create policy "Users can read their own bookmarks"
  on public.bookmarks
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can add their own bookmarks" on public.bookmarks;
create policy "Users can add their own bookmarks"
  on public.bookmarks
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own bookmarks" on public.bookmarks;
create policy "Users can delete their own bookmarks"
  on public.bookmarks
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

grant select, insert, delete on public.bookmarks to authenticated;
